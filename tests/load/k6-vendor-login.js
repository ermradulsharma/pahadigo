import http from 'k6/http';
import { check, sleep } from 'k6';

export const options = {
  scenarios: {
    login_spike: {
      executor: 'ramping-arrival-rate',
      startRate: 10,
      timeUnit: '1s',
      preAllocatedVUs: 50,
      maxVUs: 1000,
      stages: [
        { target: 100, duration: '30s' }, // 100 logins per second
        { target: 100, duration: '1m' },  // Hold at 100 logins per second
        { target: 0, duration: '30s' },
      ],
    },
  },
};

const BASE_URL = 'http://localhost:3000/api';

export default function () {
  // Using a dummy vendor payload.
  // In a real test, you'd pull from a CSV or data generated by MassSeeder
  const payload = JSON.stringify({
    email: `vendor_${__VU}@test.com`, // Simulating unique emails
    otp: '888888',
    role: 'vendor'
  });

  const params = {
    headers: {
      'Content-Type': 'application/json',
    },
  };

  const res = http.post(`${BASE_URL}/auth/verify`, payload, params);

  check(res, {
    'is status 200 or 401 or 404': (r) => r.status === 200 || r.status === 401 || r.status === 404,
    // Expecting an error if fake email doesn't exist, but checking API resilience
  });

  sleep(1);
}
